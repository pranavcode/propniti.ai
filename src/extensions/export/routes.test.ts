import { beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { getPlatform } from "@/lib/platform";
import { seed, WS } from "@/server/query.fixture";
import { CURRENT_PERIOD } from "@/seed/constants";
import { unzip } from "@/lib/export/unzip.fixture";
import * as csvRoute from "@/app/api/e/[entity]/export.csv/route";
import * as xlsxRoute from "@/app/api/e/[entity]/export.xlsx/route";
import * as pdfRoute from "@/app/api/e/[entity]/export.pdf/route";
import * as reportRoute from "@/app/api/export/report/route";
import * as statementRoute from "@/app/api/export/statement/route";

// The download routes over HTTP on the shared fixture: scope, permissions, rate limit, branding.
const state = vi.hoisted(() => ({ allow: true }));
vi.mock("@/lib/platform", async () => {
  const db = (await import("@/server/query.fixture")).emptyDb();
  const writeLimiter = { limit: async () => ({ success: state.allow }) };
  return { getPlatform: () => ({ db, writeLimiter }) };
});

const host = "propniti.test";
const req = (path: string, persona = "daniel") => new Request(`http://${host}${path}`, { headers: { host, cookie: `pn_as=${persona}; pn_ws=${WS}` } });
const p = (entity: string) => ({ params: Promise.resolve({ entity }) });
const text = async (res: Response) => new TextDecoder().decode(new Uint8Array(await res.arrayBuffer()));

beforeAll(async () => {
  const db = getPlatform().db;
  await seed(db);
  // The fixture names owner ow02 on oe02 without a row for them; statements need the owner.
  await db.prepare("INSERT INTO owners (workspace_id, id, name) VALUES ('base', 'ow02', 'Marisol Vega')").run();
});
beforeEach(() => {
  state.allow = true;
});

describe("entity list downloads", () => {
  it("XLSX has the list's rows under the persona's scope and filters, branded by default", async () => {
    const res = await xlsxRoute.GET(req("/api/e/residents/export.xlsx?f.property_id=p01,p02,p05", "marcus"), p("residents"));
    expect(res.status).toBe(200);
    expect(res.headers.get("content-type")).toBe("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
    expect(res.headers.get("content-disposition")).toMatch(/^attachment; filename="residents-\d{4}-\d{2}-\d{2}\.xlsx"$/);
    // Marcus covers p01–p03, so p05's residents are not exported even though the filter names it.
    expect(res.headers.get("x-export-rows")).toBe("4");
    const files = await unzip(new Uint8Array(await res.arrayBuffer()));
    const sheet = files["xl/worksheets/sheet1.xml"];
    expect(sheet).toContain("res-p01-u1");
    expect(sheet).not.toContain("res-p05-u1");
    expect(sheet).toMatch(/Filters: Property: (The Lofts at Riverside|Barton Creek Commons)/);
    expect(sheet).toContain("Generated by Propniti");
    expect(files["xl/media/image1.png"]).toBeDefined();
  });

  it("PDF with and without branding", async () => {
    const branded = await text(await pdfRoute.GET(req("/api/e/residents/export.pdf?f.property_id=p01"), p("residents")));
    expect(branded.startsWith("%PDF-1.4")).toBe(true);
    expect(branded).toContain("(Generated by Propniti)");
    expect(branded).toContain("(Residents)");
    const res = await pdfRoute.GET(req("/api/e/residents/export.pdf?f.property_id=p01&brand=0"), p("residents"));
    expect(res.headers.get("content-type")).toBe("application/pdf");
    const plain = await text(res);
    expect(plain).toContain("(res-p01-u1)");
    expect(plain).not.toContain("Propniti");
  });

  it("names the saved view only when it was applied", async () => {
    const applied = await text(await pdfRoute.GET(req("/api/e/vendor_1099s/export.pdf?view=missing-w9", "grace"), p("vendor_1099s")));
    expect(applied).toContain("View: Missing W-9");
    const overridden = await text(await pdfRoute.GET(req("/api/e/vendor_1099s/export.pdf?view=missing-w9&q=acme", "grace"), p("vendor_1099s")));
    expect(overridden).not.toContain("View: Missing W-9");
  });

  it("refuses roles that can't read the entity, like the list does", async () => {
    expect((await xlsxRoute.GET(req("/api/e/residents/export.xlsx", "owner"), p("residents"))).status).toBe(403);
    expect((await pdfRoute.GET(req("/api/e/residents/export.pdf", "vendor"), p("residents"))).status).toBe(403);
    expect((await pdfRoute.GET(req("/api/e/nope/export.pdf"), p("nope"))).status).toBe(404);
    expect((await pdfRoute.GET(req("/api/e/residents/export.pdf?f.nope=1"), p("residents"))).status).toBe(400);
  });

  it("shares the write rate limit with the CSV export", async () => {
    state.allow = false;
    for (const res of [
      await csvRoute.GET(req("/api/e/residents/export.csv"), p("residents")),
      await xlsxRoute.GET(req("/api/e/residents/export.xlsx"), p("residents")),
      await pdfRoute.GET(req("/api/e/residents/export.pdf"), p("residents")),
      await reportRoute.GET(req("/api/export/report?r=ar_aging&format=pdf")),
      await statementRoute.GET(req(`/api/export/statement?entity=oe01&period=${CURRENT_PERIOD}&format=pdf`)),
    ]) expect(res.status).toBe(429);
  });
});

describe("report downloads", () => {
  it("re-runs the report under the persona's scope in each format", async () => {
    const csv = await reportRoute.GET(req("/api/export/report?r=ar_aging&format=csv", "marcus"));
    expect(csv.headers.get("content-type")).toContain("text/csv");
    const bytes = new Uint8Array(await csv.arrayBuffer());
    // A UTF-8 byte-order mark, so Excel reads "–" and "·" correctly; text() drops it.
    expect([...bytes.slice(0, 3)]).toEqual([0xef, 0xbb, 0xbf]);
    const lines = new TextDecoder().decode(bytes).trim().split("\r\n");
    expect(lines[0]).toBe("Property,0–30 days,31–60,61–90,90+,Total,Charges");
    expect(lines.some((l) => l.startsWith("Inman Park Flats"))).toBe(false);
    const pdf = await text(await reportRoute.GET(req("/api/export/report?r=ar_aging&format=pdf&brand=0", "marcus")));
    expect(pdf).toContain("(Accounts receivable aging)");
    expect(pdf).not.toContain("Propniti");
    const xlsx = await reportRoute.GET(req("/api/export/report?r=rent_roll&format=xlsx", "marcus"));
    expect((await unzip(new Uint8Array(await xlsx.arrayBuffer())))["xl/worksheets/sheet1.xml"]).toContain("Scope: ");
  });

  it("checks the role, the property scope, the format and the builder spec", async () => {
    expect((await reportRoute.GET(req("/api/export/report?r=pnl&format=pdf", "lena"))).status).toBe(403);
    expect((await reportRoute.GET(req("/api/export/report?r=pnl&format=pdf&property=p05", "marcus"))).status).toBe(403);
    expect((await reportRoute.GET(req("/api/export/report?r=pnl&format=docx"))).status).toBe(400);
    expect((await reportRoute.GET(req("/api/export/report?r=nope&format=csv"))).status).toBe(404);
    expect((await reportRoute.GET(req("/api/export/report?r=ask&measure=expense&group=property&from=2026-01&to=2026-09&format=csv&properties=p05", "marcus"))).status).toBe(403);
    expect((await reportRoute.GET(req("/api/export/report?r=ask&measure=nope&group=property&format=csv"))).status).toBe(400);
    const ok = await reportRoute.GET(req("/api/export/report?r=ask&measure=expense&group=property&from=2026-01&to=2026-09&compare=budget&format=csv"));
    expect(ok.status).toBe(200);
    expect((await ok.text()).split("\r\n")[0]).toBe("Property,Operating expense,Budget,Variance,Variance %");
  });
});

describe("owner statement downloads", () => {
  const url = (entity: string, format = "pdf") => `/api/export/statement?entity=${entity}&period=${CURRENT_PERIOD}&format=${format}`;

  it("lets the owner and in-scope staff download, and no one else", async () => {
    const own = await statementRoute.GET(req(url("oe01"), "owner"));
    expect(own.status).toBe(200);
    const pdf = await text(own);
    expect(pdf).toContain("Bluebonnet Residential Fund II, LLC");
    expect(pdf).toContain("(Generated by Propniti)");
    expect((await statementRoute.GET(req(url("oe02"), "owner"))).status).toBe(403);
    expect((await statementRoute.GET(req(url("oe02"), "marcus"))).status).toBe(403);
    expect((await statementRoute.GET(req(url("oe01"), "lena"))).status).toBe(403);
    expect((await statementRoute.GET(req(url("oe02"), "daniel"))).status).toBe(200);
    expect((await statementRoute.GET(req(url("nope")))).status).toBe(404);
    expect((await statementRoute.GET(req(`/api/export/statement?entity=oe01&period=2026-13&format=pdf`))).status).toBe(400);
  });

  it("CSV is plain data even when branding is on", async () => {
    const csv = await (await statementRoute.GET(req(url("oe01", "csv"), "owner"))).text();
    expect(csv.split("\r\n")[0]).toBe("Line,Detail,Amount");
    expect(csv).not.toContain("Propniti");
  });
});
