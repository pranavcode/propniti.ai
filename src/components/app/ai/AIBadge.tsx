"use client";

import { Cpu, Database, Sparkles } from "lucide-react";
import { cn } from "@/lib/utils";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";

// Honest provenance for any AI output (plan addendum 4): a live model call, a stored result from
// an earlier run, or the deterministic rule fallback when no model was available.
export type AISource = "live" | "precomputed" | "rules";

const COPY: Record<AISource, { label: string; tip: string; icon: typeof Sparkles }> = {
  live: { label: "AI", tip: "Generated just now by a live model call.", icon: Sparkles },
  precomputed: { label: "AI · saved", tip: "Generated by an earlier agent run and stored; regenerate for a fresh answer.", icon: Database },
  rules: { label: "Rule-based fallback", tip: "No model was available, so fixed rules produced this. Figures are still computed from your data.", icon: Cpu },
};

export function AIBadge({ source = "live", model, className, size = "sm" }: { source?: AISource; model?: string; className?: string; size?: "xs" | "sm" }) {
  const c = COPY[source];
  const Icon = c.icon;
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex shrink-0 items-center gap-1 rounded font-medium whitespace-nowrap ring-1 ring-inset outline-none focus-visible:ring-2 focus-visible:ring-ring/60",
            size === "xs" ? "h-[18px] px-1 text-[10.5px]" : "h-5 px-1.5 text-[11px]",
            source === "rules" ? "bg-muted text-muted-foreground ring-border" : "bg-tone-ai/[0.07] text-tone-ai ring-tone-ai/25",
            className,
          )}
        >
          <Icon className="size-3" aria-hidden />
          {c.label}
          {model && source !== "rules" && <span className="font-normal opacity-75">· {model}</span>}
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-64">{c.tip}{model ? ` Model: ${model}.` : ""}</TooltipContent>
    </Tooltip>
  );
}

// 0–1 → High / Medium / Low (brief §4.2: a label plus reasons beats a bare percentage).
export function confidenceLabel(c: number): "High" | "Medium" | "Low" {
  return c >= 0.8 ? "High" : c >= 0.55 ? "Medium" : "Low";
}

export function Confidence({ value, className }: { value: number; className?: string }) {
  const label = confidenceLabel(value);
  const bars = label === "High" ? 3 : label === "Medium" ? 2 : 1;
  return (
    <span className={cn("inline-flex items-center gap-1.5 text-[11.5px] text-muted-foreground", className)} title={`${Math.round(value * 100)}% confidence`}>
      <span className="flex items-end gap-px" aria-hidden>
        {[1, 2, 3].map((i) => <span key={i} className={cn("w-[3px] rounded-[1px]", i <= bars ? (label === "Low" ? "bg-tone-warning" : "bg-tone-ai") : "bg-border")} style={{ height: 4 + i * 3 }} />)}
      </span>
      <span><span className="font-medium text-foreground">{label}</span> confidence · {Math.round(value * 100)}%</span>
    </span>
  );
}
