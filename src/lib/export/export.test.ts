import { describe, expect, it } from "vitest";
import { display } from "./cells";
import { toCsv } from "./csv";
import { pdfString, toPdf } from "./pdf";
import type { ExportDoc } from "./types";
import { colName, toXlsx, xmlText } from "./xlsx";
import { unzip } from "./unzip.fixture";
import { parseXlsx } from "@/extensions/import/parse";

const doc = (over: Partial<ExportDoc> = {}): ExportDoc => ({
  title: "Residents",
  columns: [{ label: "ID" }, { label: "Name" }, { label: "Balance", kind: "money" }, { label: "Move-in", kind: "date" }, { label: "Occupancy", kind: "percent" }],
  rows: [
    ["res-1", "Ana <Diaz> & Co", -1240, "2026-11-04", 0.953],
    ["res-2", "=HYPERLINK(\"http://x\")", 1450.5, null, null],
    ["res-3", "Paren (test) \\ back\u0007slash", 0, "2025-01-31", 1],
  ],
  branded: true,
  scope: "Texas region · 14 properties",
  filters: ["Status: Current", 'Search: "diaz"'],
  generatedAt: "2026-11-04T09:41:00Z",
  ...over,
});

describe("cell display (en-US, like the UI)", () => {
  it("formats money, dates, percents and booleans", () => {
    expect(display(-1240, "money")).toBe("−$1,240.00");
    expect(display("2026-11-04", "date")).toBe("Nov 4, 2026");
    expect(display("2026-11-04T09:41:00Z", "datetime")).toBe("Nov 4, 2026, 9:41 AM");
    expect(display(0.953, "percent")).toBe("95.3%");
    expect(display(true, "bool")).toBe("Yes");
    expect(display(null, "money")).toBe("");
  });
});

describe("CSV", () => {
  it("is plain data with quoting and formula-injection protection", () => {
    const csv = toCsv(doc());
    const lines = csv.trim().split("\r\n");
    expect(lines[0]).toBe("ID,Name,Balance,Move-in,Occupancy");
    expect(lines[2]).toBe(`res-2,"'=HYPERLINK(""http://x"")",1450.5,,`);
    expect(lines[1]).toContain("-1240");
    expect(csv).not.toContain("Propniti");
  });
});

describe("XLSX", () => {
  it("is a valid package with one sheet, real numbers and dates, and styles", async () => {
    const files = await unzip(await toXlsx(doc({ branded: false })));
    expect(Object.keys(files).sort()).toEqual(["[Content_Types].xml", "_rels/.rels", "xl/_rels/workbook.xml.rels", "xl/styles.xml", "xl/workbook.xml", "xl/worksheets/sheet1.xml"]);
    const sheet = files["xl/worksheets/sheet1.xml"];
    expect(sheet).toContain('<c r="A1" t="inlineStr" s="9"><is><t xml:space="preserve">Residents</t>');
    // Unbranded: title, blank row, header on row 3, data from row 4.
    expect(sheet).toContain('<c r="C3" t="inlineStr" s="11">');
    expect(sheet).toContain('<c r="C4" s="2"><v>-1240</v></c>');
    expect(sheet).toContain(`<c r="D4" s="3"><v>${(Date.UTC(2026, 10, 4) - Date.UTC(1899, 11, 30)) / 86_400_000}</v></c>`);
    expect(sheet).toContain('<c r="E4" s="5"><v>0.953</v></c>');
    expect(sheet).toContain('<pane ySplit="3" topLeftCell="A4"');
    expect(files["xl/styles.xml"]).toContain('formatCode="&quot;$&quot;#,##0.00;-&quot;$&quot;#,##0.00"');
    expect(files["xl/workbook.xml"]).toContain('<sheet name="Residents"');
  });

  it("escapes XML, drops control characters and never writes a formula", async () => {
    const sheet = (await unzip(await toXlsx(doc())))["xl/worksheets/sheet1.xml"];
    expect(sheet).toContain("Ana &lt;Diaz&gt; &amp; Co");
    expect(sheet).toContain("Paren (test) \\ backslash");
    expect(sheet).not.toMatch(/<f>/);
    // Formula-looking text is an inline string with Excel's quotePrefix style (s=8).
    expect(sheet).toMatch(/<c r="B\d+" t="inlineStr" s="8"><is><t xml:space="preserve">=HYPERLINK\(&quot;http:\/\/x&quot;\)<\/t>/);
    expect(xmlText("a\u0000b\uFFFEc\uD800")).toBe("abc");
    expect(colName(0)).toBe("A");
    expect(colName(26)).toBe("AA");
    expect(colName(701)).toBe("ZZ");
  });

  it("adds the logo, scope, filters, time and footer only when branded", async () => {
    const branded = await unzip(await toXlsx(doc()));
    const sheet = branded["xl/worksheets/sheet1.xml"];
    expect(branded["xl/media/image1.png"]).toMatch(/^png:\d+$/);
    expect(branded["xl/drawings/drawing1.xml"]).toContain('r:embed="rId1"');
    expect(branded["[Content_Types].xml"]).toContain('Extension="png"');
    expect(sheet).toContain('<drawing r:id="rId1"/>');
    expect(sheet).toContain("Scope: Texas region · 14 properties");
    expect(sheet).toContain("Filters: Status: Current; Search: &quot;diaz&quot;");
    expect(sheet).toContain("Generated Nov 4, 2026, 9:41 AM PT");
    expect(sheet).toContain("Generated by Propniti");
    expect(sheet).toContain("<oddFooter>&amp;LGenerated by Propniti");

    const plain = await unzip(await toXlsx(doc({ branded: false })));
    expect(Object.keys(plain).some((k) => k.includes("media") || k.includes("drawing"))).toBe(false);
    expect(plain["xl/worksheets/sheet1.xml"]).not.toMatch(/Propniti|Scope:|Filters:|Generated/);
  });

  it("reads back through the app's own XLSX importer", async () => {
    const table = await parseXlsx(await toXlsx(doc({ branded: false })));
    expect(table[0]).toEqual(["Residents"]);
    expect(table[1]).toEqual(["ID", "Name", "Balance", "Move-in", "Occupancy"]);
    expect(table[2]).toEqual(["res-1", "Ana <Diaz> & Co", "-1240", "2026-11-04", "0.953"]);
    expect(table[3][1]).toBe('=HYPERLINK("http://x")');
  });

  it("shows the row-cap note on every copy", async () => {
    for (const branded of [true, false]) {
      const sheet = (await unzip(await toXlsx(doc({ branded, note: "Showing the first 10,000 of 12,000 rows." }))))["xl/worksheets/sheet1.xml"];
      expect(sheet).toContain("Showing the first 10,000 of 12,000 rows.");
    }
  });
});

describe("PDF", () => {
  const text = (b: Uint8Array) => new TextDecoder().decode(b);

  it("has a valid header, object table and trailer", () => {
    const out = text(toPdf(doc()));
    expect(out.startsWith("%PDF-1.4\n")).toBe(true);
    expect(out.trimEnd().endsWith("%%EOF")).toBe(true);
    const xref = Number(out.match(/startxref\n(\d+)\n/)![1]);
    expect(out.slice(xref, xref + 4)).toBe("xref");
    const [, count] = out.slice(xref).match(/^xref\n0 (\d+)\n/)!;
    const entries = out.slice(xref).split("\n").slice(3, 2 + Number(count));
    entries.forEach((e, i) => expect(out.startsWith(`${i + 1} 0 obj\n`, Number(e.slice(0, 10)))).toBe(true));
    for (const m of out.matchAll(/<< \/Length (\d+) >>\nstream\n/g)) {
      const start = m.index! + m[0].length;
      expect(out.slice(start + Number(m[1]), start + Number(m[1]) + 10)).toBe("\nendstream");
    }
    expect(out).toContain("/BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding");
    expect(/[^\x09\x0a\x0d\x20-\x7e]/.test(out)).toBe(false);
  });

  it("formats values like the UI and escapes PDF strings", () => {
    const out = text(toPdf(doc()));
    expect(out).toContain("(-$1,240.00)");
    expect(out).toContain("(Nov 4, 2026)");
    expect(out).toContain("(95.3%)");
    expect(out).toContain("(Paren \\(test\\) \\\\ back slash)");
    expect(pdfString("Café · – ✓")).toBe("(Caf\\351 \\267 \\226 ?)");
  });

  it("adds the logo, scope, filters, time and footer only when branded", () => {
    const branded = text(toPdf(doc()));
    expect(branded).toContain("(Propniti)");
    expect(branded).toContain("(Scope: Texas region \\267 14 properties)");
    expect(branded).toContain("(Generated Nov 4, 2026, 9:41 AM PT)");
    expect(branded).toContain("(Generated by Propniti)");
    expect(branded).toMatch(/0 0\.412 0\.416 rg/);
    const plain = text(toPdf(doc({ branded: false })));
    expect(plain).toContain("(Residents)");
    expect(plain).not.toMatch(/Propniti|Scope:|Filters:|Generated|0\.412 0\.416 rg/);
  });

  it("paginates long tables and repeats the header", () => {
    const rows = Array.from({ length: 300 }, (_, i) => [`res-${i}`, `Resident ${i}`, i, "2026-01-01", 0.5]);
    const out = text(toPdf(doc({ rows })));
    const pages = Number(out.match(/\/Count (\d+)/)![1]);
    expect(pages).toBeGreaterThan(3);
    expect(out.match(/\(Balance\) Tj/g)).toHaveLength(pages);
    expect(out).toContain(`(Page ${pages} of ${pages})`);
    expect(out).toContain("(Resident 299)");
  });

  it("uses landscape for wide tables", () => {
    const columns = Array.from({ length: 9 }, (_, i) => ({ label: `C${i}` }));
    expect(text(toPdf(doc({ columns, rows: [] })))).toContain("/MediaBox [0 0 792 612]");
    expect(text(toPdf(doc()))).toContain("/MediaBox [0 0 612 792]");
  });
});
