// One exported table, written as CSV, XLSX or PDF. Writers are pure and run in the browser,
// Node and Workers alike (no Node built-ins, no dependencies).

export const EXPORT_CAP = 10_000;
export const FORMATS = ["csv", "xlsx", "pdf"] as const;
export type Format = (typeof FORMATS)[number];

// How a column's values are shown: money in dollars, dates as YYYY-MM-DD, datetimes as ISO,
// percent as a ratio (0.953 is 95.3%).
export type Kind = "text" | "money" | "number" | "date" | "datetime" | "percent" | "bool";
export type Column = { label: string; kind?: Kind };
export type Cell = string | number | boolean | null | undefined;

export type ExportDoc = {
  title: string;
  columns: Column[];
  rows: Cell[][];
  // Branded copies add the logo, scope, filters, generated-at time and a "Generated by Propniti"
  // footer to XLSX and PDF. Unbranded copies are the title and the data only.
  branded: boolean;
  scope: string;
  filters: string[];
  generatedAt: string;                   // ISO, from the demo clock
  note?: string;                         // shown on every copy, e.g. the row cap
};

export const capNote = (total: number) => `Showing the first ${EXPORT_CAP.toLocaleString("en-US")} of ${total.toLocaleString("en-US")} rows. Narrow the filters to export the rest.`;
