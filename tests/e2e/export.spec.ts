import { readFile } from "node:fs/promises";
import { expect, test, type Page } from "@playwright/test";
import { as, go, watch } from "./helpers";
import { unzip } from "../../src/lib/export/unzip.fixture";

// Download menu on the residents list: CSV, Excel and PDF, with and without Propniti branding.
// The files are built on the server from the list's URL state (filters, search, scope).

async function download(page: Page, item: RegExp) {
  await page.getByRole("button", { name: "Download", exact: true }).click();
  const [file] = await Promise.all([page.waitForEvent("download"), page.getByRole("menuitem", { name: item }).click()]);
  return { name: file.suggestedFilename(), bytes: new Uint8Array(await readFile((await file.path())!)) };
}

async function setBranding(page: Page, on: boolean) {
  await page.getByRole("button", { name: "Download", exact: true }).click();
  const box = page.getByRole("menuitemcheckbox", { name: /Include Propniti branding/ });
  if ((await box.getAttribute("aria-checked")) !== String(on)) await box.click();
  await expect(box).toHaveAttribute("aria-checked", String(on));
  await page.keyboard.press("Escape");
}

test("residents list downloads as CSV, Excel and PDF, branded and plain", async ({ page, context }) => {
  const errors = watch(page);
  await as(context, "marcus");
  await go(page, "/app/residents?q=a");
  await page.getByRole("button", { name: "Download", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: /CSV has no branding/ })).toBeVisible();
  await page.keyboard.press("Escape");

  const csv = await download(page, /^CSV/);
  expect(csv.name).toMatch(/^residents-\d{4}-\d{2}-\d{2}\.csv$/);
  const lines = new TextDecoder().decode(csv.bytes).trim().split("\r\n");
  expect(lines[0]).toMatch(/^ID,/);
  expect(lines.length).toBeGreaterThan(1);
  expect(lines.join("\n")).not.toContain("Propniti");

  await setBranding(page, true);
  const xlsx = await download(page, /^Excel/);
  expect(xlsx.name).toMatch(/\.xlsx$/);
  const book = await unzip(xlsx.bytes);
  expect(book["xl/worksheets/sheet1.xml"]).toContain("Generated by Propniti");
  expect(book["xl/worksheets/sheet1.xml"]).toContain('Search: &quot;a&quot;');
  expect(book["xl/media/image1.png"]).toBeDefined();
  const pdf = await download(page, /^PDF/);
  const pdfText = new TextDecoder().decode(pdf.bytes);
  expect(pdfText.startsWith("%PDF-1.4")).toBe(true);
  expect(pdfText).toContain("(Generated by Propniti)");

  // Turned off, the choice sticks for this browser across reloads.
  await setBranding(page, false);
  await page.reload();
  await page.getByRole("button", { name: "Download", exact: true }).click();
  await expect(page.getByRole("menuitemcheckbox", { name: /Include Propniti branding/ })).toHaveAttribute("aria-checked", "false");
  await page.keyboard.press("Escape");
  const plainXlsx = await unzip((await download(page, /^Excel/)).bytes);
  expect(plainXlsx["xl/worksheets/sheet1.xml"]).not.toMatch(/Propniti|Scope:/);
  expect(Object.keys(plainXlsx).some((k) => k.includes("media"))).toBe(false);
  const plainPdf = new TextDecoder().decode((await download(page, /^PDF/)).bytes);
  expect(plainPdf).toContain("(Residents)");
  expect(plainPdf).not.toContain("Propniti");
  expect(errors).toEqual([]);
});
